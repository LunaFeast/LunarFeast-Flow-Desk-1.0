/* --看 给一个默认支名（他可改）：从「本轮说明」那一串里挑出形状允许的字符凑一个尾段，
   凑不出来就用发布日期顶着。说明里那串中文（「外46 tauri 通道」这一类）挑剩的就是 ASCII 那几段，
   比如「外46 搬 tauri 数据通道」→ feature/tweak/46-tauri —— 认得出是谁就够了，名字他要改就改这一行。
   默认落在四类里的「优化」那一类（这一轮做的多半是已有功能的小修；开新功能或走重构他自己改那一行，
   界面上类型那一格跟着改）。生成出来一定被 认支类 认得出；认不出就退回 feature/tweak/round-<日期>，
   绝不回一个不属于四类的名字。 */
export function 支名默认(说明, 日子){
  const 段 = (String(说明 || '').match(/[A-Za-z0-9][A-Za-z0-9._-]*/g) || [])
    .map(s => s.toLowerCase())
    .filter(s => s.length > 1 && !/^(mjs|cjs|js|json|rs|html|git|md|exe|node|src)$/.test(s));
  const 尾 = [...new Set(段)].join('-').slice(0, 48).replace(/[-._]+$/, '');
  const 天 = String(日子 || new Date().toISOString().slice(0, 10).replace(/-/g, ''));
  const 名 = 'feature/tweak/' + (尾 || 'round-' + 天.replace(/[-.]+/g, '-'));
  return 认支类(名) ? 名 : 'feature/tweak/round-' + 天.replace(/[-.]+/g, '-');
}
