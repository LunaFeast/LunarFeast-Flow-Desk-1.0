export function 拼清单(项){
  const 段 = (项.笔 || []).map(x => {
    const 行 = [];
    行.push('【' + x.名 + '】' + x.副题);
    行.push('  会不会动 = ' + x.会动);
    行.push('  现在挂的号 = ' + (x.现在 || '（这一家还没有过号）'));
    行.push('  会迭代成 = ' + x.会成);
    if(x.话) for(const h of x.话) 行.push('  # ' + h);
    if(x.描述 !== null) 行.push('  更新描述 = ' + x.描述);
    行.push(x.份.length ? '  动了哪些份 =' : '  动了哪些份 = 没有');
    for(const f of x.份) 行.push('    ' + f);
    return 行.join('\n');
  });
  const 顶 = ['版本基线 = ' + 项.基线, 基线注, '',
    '分支类型 = ' + (项.分支类型 || ''), 类注, '', '提交分支 = ' + (项.提交分支 || ''), 支注, '',
    ...摊(项.本轮说明), 说明注];
  return 头 + '\n\n' + 顶.join('\n') + '\n\n' + 段.join('\n\n') + '\n\n' + 脚注 + '\n';
}

/* 顶上那一行「本轮说明 =」的写法：一段自由文本摊成几行（一行一句），只有一行时还是一行的样子 */
const 摊 = 文 => String(文 == null ? '' : 文).split(/\r?\n/).map(t => '本轮说明 = ' + t);

/* 把那一格读回来：只认顶上那三样（版本基线、提交分支、本轮说明）与每一笔的【名字】、那一笔底下的更新描述。
   他改坏了（空、多打了字）也不报错在这一层，交给发布脚本与 pr.mjs 那一句「停下来」说清楚。 */
/* 更新描述可以一行一句、连着几行（界面上粘进来的一段话就是几行）：读的时候按行收，
   写的时候一行一行摊回去。只有一行的还是原来那一行的样子，手改的人看不出差别。本轮说明同一套写法。 */
function 收描述(存, 名, 值){
  const 老 = 存[名];
  存[名] = 老 === undefined ? [值] : 存[名].concat(值);
}
export function 读清单(文){
  const 出 = { 基线:'', 有基线行:false, 分支类型:'', 有类型行:false, 提交分支:'', 有支行:false, 本轮说明:'', 有本轮说明行:false, 描述:{}, 那笔:[] };
  const 收 = {}, 收说明 = [];
  let 在 = '';
  for(const 行 of String(文 || '').split(/\r?\n/)){
    if(/^\s*#/.test(行)) continue;                                  /* 说明行整行跳过 */
    const m = /^[ \t]*【(.+?)】/.exec(行);
    if(m){ 在 = m[1].trim(); 出.那笔.push(在); continue; }
    const d = /^[ \t]*更新描述[ \t]*=[ \t]*(.*)$/.exec(行);
    if(d){ if(在) 收描述(收, 在, d[1]); continue; }
    if(在) continue;                                                /* 一笔里的其余各行：读的时候不认，只当给你看 */
    const y = /^分支类型[ \t]*=[ \t]*(.*)$/.exec(行);
    if(y){ if(!出.有类型行){ 出.有类型行 = true; 出.分支类型 = y[1].trim(); } continue; }
    const g = /^提交分支[ \t]*=[ \t]*(.*)$/.exec(行);
    if(g){ if(!出.有支行){ 出.有支行 = true; 出.提交分支 = g[1].trim(); } continue; }
    const r = /^本轮说明[ \t]*=[ \t]*(.*)$/.exec(行);
    if(r){ 出.有本轮说明行 = true; 收说明.push(r[1]); continue; }
    const b = /^版本基线[ \t]*=[ \t]*(.*)$/.exec(行);
    if(b && b[1].trim()){ 出.有基线行 = true; 出.基线 = b[1].trim(); }
  }
  if(收说明.length) 出.本轮说明 = 收说明.map(s => s.trim()).join('\n');
  for(const k of Object.keys(收)) 出.描述[k] = 收[k].map(s => s.trim()).join('\n');
  return 出;
}

/* 界面上那一张表用的读法：除了能改的四样，把「只给你看」的那几行也一并读回来
   （会不会动 / 现在挂的号 / 会迭代成 / 动了哪些份）。形状只在这颗里认一遍 ——
   界面上看到的和 --看 落下来的必须是同一份文件量出来的，不能各parse各的。
   顶上那三行（版本基线 / 提交分支 / 本轮说明）与 读清单 认的是同一串，两颗尺对同一份文件必须说同一句话。 */
export function 读清单显示(文){
  const 出 = { 基线:'', 有基线行:false, 分支类型:'', 有类型行:false, 提交分支:'', 有支行:false, 本轮说明:'', 有本轮说明行:false, 笔:[] };
  let 当 = null;
  const 收说明 = [];
  const 掐 = s => String(s == null ? '' : s).trim();
  for(const 行 of String(文 || '').split(/\r?\n/)){
    const 参 = /^[ \t]*#[ \t]*参照文字[^：]*：(.*)$/.exec(行);   /* 那一行行首带 #（别的行不算数据），界面上拿它当输入框的提示 */
    if(参){ if(当) 当.参照 = 掐(参[1]); continue; }
    if(/^\s*#/.test(行)) continue;
    const m = /^[ \t]*【(.+?)】/.exec(行);
    if(m){ 当 = { 名:掐(m[1]), 副题:掐(行.replace(m[0], '')), 会不会动:'', 现在挂的号:'', 会迭代成:'', 份:[], 描述:[], 有描述:false, 参照:'' }; 出.笔.push(当); continue; }
    if(!当){
      const b = /^版本基线[ \t]*=[ \t]*(.*)$/.exec(行);
      if(b && b[1].trim()){ 出.有基线行 = true; 出.基线 = b[1].trim(); continue; }
      const y = /^分支类型[ \t]*=[ \t]*(.*)$/.exec(行);
      if(y){ if(!出.有类型行){ 出.有类型行 = true; 出.分支类型 = y[1].trim(); } continue; }
      const g = /^提交分支[ \t]*=[ \t]*(.*)$/.exec(行);
      if(g){ if(!出.有支行){ 出.有支行 = true; 出.提交分支 = g[1].trim(); } continue; }
      const r = /^本轮说明[ \t]*=[ \t]*(.*)$/.exec(行);
      if(r){ 出.有本轮说明行 = true; 收说明.push(r[1]); }
      continue;
    }
    let k = /^[ \t]*(会不会动|现在挂的号|会迭代成)[ \t]*=[ \t]*(.*)$/.exec(行);
    if(k){ 当[k[1]] = 掐(k[2]); continue; }
    k = /^[ \t]*更新描述[ \t]*=[ \t]*(.*)$/.exec(行);
    if(k){ 当.有描述 = true; 当.描述.push(k[1]); continue; }
    k = /^[ \t]*动了哪些份[ \t]*=[ \t]*(.*)$/.exec(行);
    if(k){ if(掐(k[2]) && 掐(k[2]) !== '没有') 当.份.push(掐(k[2])); continue; }
    k = /^[ \t]{4,}(\S.*)$/.exec(行);                                /* 份那一摊：比上面多缩一层的裸路径 */
    if(k) 当.份.push(掐(k[1]));
  }
  if(收说明.length) 出.本轮说明 = 收说明.map(s => s.trim()).join('\n');
  /* 描述：整笔没有「更新描述 =」那一行就是 null（这一笔不落笔，界面上不给框），有就是那一串（可以是空串）。 */
  for(const b of 出.笔){ b.描述 = b.有描述 ? b.描述.join('\n') : null; delete b.有描述; }
  return 出;
}

/* 只换能改的那五样（版本基线、分支类型、提交分支、本轮说明、每一笔的更新描述），其余各行原样留着
   （量出来的号、份，一颗都不动）。连着几行的就摊成几行同名的行，读回去还是那几行。 */
export function 改清单(文, 项){
  const 出 = [];
  let 在 = '';
  let 换过了 = false;
  let 换过类型 = 项.分支类型 == null, 换过支 = 项.提交分支 == null, 换过说明 = 项.本轮说明 == null;
  const 摊描述 = s => String(s == null ? '' : s).split(/\r?\n/).map(t => '  更新描述 = ' + t);
  for(const 行 of String(文 || '').split(/\r?\n/)){
    const b = /^版本基线[ \t]*=[ \t]*(.*)$/.exec(行);
    if(b && 项.基线 != null){ 出.push('版本基线 = ' + 项.基线); continue; }
    const m = /^[ \t]*【(.+?)】/.exec(行);
    if(m){
      /* 老那份清单里没有那三行（「分支类型」是 2026-10-12 加的，另两行是 2026-10-11 加的）：
         界面上改过了就在第一笔之前按 拼清单 顶上那个顺序补上，不补就等于那一格白改 */
      if(!换过类型 || !换过支 || !换过说明){
        if(!换过类型){ 出.push('分支类型 = ' + 项.分支类型, ''); 换过类型 = true; }
        if(!换过支){ 出.push('提交分支 = ' + 项.提交分支, ''); 换过支 = true; }
        if(!换过说明){ 出.push(...摊(项.本轮说明), ''); 换过说明 = true; }
      }
      在 = m[1].trim();
      换过了 = false;
      const 新 = 项.描述 ? 项.描述[在] : undefined;
      if(新 === undefined){ 出.push(行); continue; }
      出.push(行); 出.push(...摊描述(新)); 换过了 = true;                /* 新的紧跟【】那一行，旧的下面那些丢掉 */
      continue;
    }
    const y = /^分支类型[ \t]*=[ \t]*(.*)$/.exec(行);
    if(y && 项.分支类型 != null){ if(!换过类型){ 出.push('分支类型 = ' + 项.分支类型); 换过类型 = true; } continue; }
    const g = /^提交分支[ \t]*=[ \t]*(.*)$/.exec(行);
    if(g && 项.提交分支 != null){ if(!换过支){ 出.push('提交分支 = ' + 项.提交分支); 换过支 = true; } continue; }
    const r = /^本轮说明[ \t]*=[ \t]*(.*)$/.exec(行);
    if(r && 项.本轮说明 != null){ if(!换过说明){ 出.push(...摊(项.本轮说明)); 换过说明 = true; } continue; }
    const d = /^[ \t]*更新描述[ \t]*=[ \t]*(.*)$/.exec(行);
    if(d && 在 && 换过了) continue;
    出.push(行);
  }
  return 出.join('\n');
}

