/* 四层里的第一层 · 定期备份那几道判断（外46 三 批二 · 搬 backup.cjs 里"不碰盘"的那一手）
   ------------------------------------------------------------
   主进程那边抄这件事在 src\pack\backup.cjs 里（run / prune / last / check 四颗通道都从它出），
   那一份把 fs / path / now 都从外面递进去，所以它自己不认识 Electron；壳这一头链不着 Node，
   那份里"只看字符串就能定"的那几手全挪到这一格，剩下的（走树、抄字节、改名、收旧份）在第三层动手。
   这一格只管四件事：
     · 名字 —— 时间戳那一大式怎么写、哪几颗文件夹算"我抄的那一份"、哪一颗是半拉子；
     · 时刻 —— 从文件夹名读回那一刻、按哪一档隔多久、到点没、下一颗表设到哪一刻；
     · 落点 —— 这一趟备份该不该停在这儿：没定落点、落点带着回退写法、落点跑在被抄的那几处里面、
       落点跑进程序这一棵树里（这一条是壳这一头新添的一道闸，Electron 那边没有 ——
       备份写进仓就等于把自己的数据塞回代码那一棵树，下一趟更新和公开面扫描都得跟着倒霉）；
     · 账 —— 收旧份时该收哪几颗、多大那一句怎么说。
   这里只算字符串与数；盘上到底有没有那一格、抄不抄得动，由第三层问。
   句子里的落点例子一律写成「某处\一棵树」那种中性写法，仓里的字面不留下这台机器的地盘。 */
use chrono::{Datelike, Local, NaiveDate, NaiveDateTime, NaiveTime, Timelike, TimeZone};

/// 备份清单那一份的名字：认不认得出"这是我抄的那一份"就看它在不在（照 backup.cjs 的 MANIFEST）
pub const 清档名: &str = "备份清单.txt";
/// 半成品那一颗的尾巴：全抄完了才改名，中途崩了就剩这一颗没改名的（照 backup.cjs 的 DOING）
pub const 半拉子尾: &str = ".正在写";

/* ---------- 一、名字 ---------- */

/// 那一刻写成文件夹名：FD-年-月-日-时分（月和日补零，时与分并排不加分隔）
/// 照 stampOf 那一颗：看的是自己表上的那一个时刻，不是 UTC
pub fn 时间戳(刻: NaiveDateTime) -> String {
    format!(
        "FD-{:04}-{:02}-{:02}-{:02}{:02}",
        刻.year(),
        刻.month(),
        刻.day(),
        刻.hour(),
        刻.minute()
    )
}

/// 这个名字是不是"我抄的那一份"（FD-\d{4}-\d{2}-\d{2}-\d{4}）：收旧份与找上一次都只认这一式
pub fn 是自家造的那一颗(名: &str) -> bool {
    let 字: Vec<char> = 名.chars().collect();
    if 字.len() != 18 || 字[0] != 'F' || 字[1] != 'D' {
        return false;
    }
    /* 分隔钉死在 2 / 7 / 10 / 13 四处，其余十四位全得是数 */
    if [2usize, 7, 10, 13].iter().any(|i| 字[*i] != '-') {
        return false;
    }
    [(3, 7), (8, 10), (11, 13), (14, 18)]
        .iter()
        .all(|(起, 止)| 字[*起..*止].iter().all(|c| c.is_ascii_digit()))
}

/// 这一颗是不是没改名的半成品：去掉尾巴要合"自家造的那一颗"那一式，且尾巴对得上
/// （照 backup.cjs 的 半成品：slice(0, -DOING.length) + endsWith(DOING)，两条都中才算）
pub fn 是半拉子的那一颗(名: &str) -> bool {
    let 尾 = 半拉子尾.chars().count();
    let 字: Vec<char> = 名.chars().collect();
    if 字.len() <= 尾 || !名.ends_with(半拉子尾) {
        return false;
    }
    let 去尾: String = 字[..字.len() - 尾].iter().collect();
    是自家造的那一颗(&去尾)
}

/// 时间戳那串名字读回那一刻（毫秒，本机墙上时间）：认不出那一式就是 0
/// 照 stampTime：new Date(年, 月-1, 日, 时, 分).getTime()
pub fn 戳回时刻(名: &str) -> i64 {
    if !是自家造的那一颗(名) {
        return 0;
    }
    let 取 = |起: usize, 长: usize| -> i32 {
        名.chars()
            .skip(起)
            .take(长)
            .collect::<String>()
            .parse()
            .unwrap_or(0)
    };
    let (年, 月, 日, 时, 分) = (取(3, 4), 取(8, 2), 取(11, 2), 取(14, 2), 取(16, 2));
    let 那日 = match NaiveDate::from_ymd_opt(年, 月.max(1) as u32, 日.max(1) as u32) {
        Some(d) => d,
        None => return 0,
    };
    let 那一刻 = match NaiveTime::from_hms_opt(时.max(0) as u32, 分.max(0) as u32, 0) {
        Some(t) => t,
        None => return 0,
    };
    match Local.from_local_datetime(&NaiveDateTime::new(那日, 那一刻)) {
        /* 撞上夏令时那两可的时刻：取早的那一个，跟 JS 那一头的挑法同一手 */
        chrono::LocalResult::Single(t) => t.timestamp_millis(),
        chrono::LocalResult::Ambiguous(早, _) => 早.timestamp_millis(),
        _ => 0,
    }
}

/* ---------- 二、隔多久、到点没、下一回 ---------- */

/// 那一档隔多久（毫秒）：认不出的档与「off」都算 0 —— 0 就是"不排表"（照 backup.cjs 的 隔）
pub fn 间隔(那一档: &str) -> i64 {
    match 那一档 {
        "day" => 86_400_000,
        "3d" => 259_200_000,
        "week" => 604_800_000,
        _ => 0,
    }
}

/// 到点没：没开着、或那一档是 0 都不算到点；从没抄过就当场算到点（照 due）
pub fn 到点没(开着: bool, 那一档: &str, 上回时: i64, 现在: i64) -> bool {
    let 分 = 间隔(那一档);
    if !开着 || 分 == 0 {
        return false;
    }
    if 上回时 == 0 {
        return true;
    }
    现在 - 上回时 >= 分
}

/// 下一回到点的那一刻：没开着回 0；没抄过就从"现在"起算（照 nextAt）
pub fn 下一回(开着: bool, 那一档: &str, 上回时: i64, 现在: i64) -> i64 {
    let 分 = 间隔(那一档);
    if !开着 || 分 == 0 {
        return 0;
    }
    let 底 = if 上回时 == 0 { 现在 } else { 上回时 };
    底 + 分
}

/* ---------- 三、落点那一道闸 ---------- */

/// 认不认这一串是绝对地址：「字母 + 冒号 + 斜杠」那种盘符写法（两种斜杠都算）、
/// 或者两个斜杠打头的 UNC。跟 Node 的 path.isAbsolute 在 Windows 上同一个口径。
pub fn 是绝对地址(串: &str) -> bool {
    let 字: Vec<char> = 串.chars().collect();
    if 字.len() >= 2 && 字[0] == '\\' && 字[1] == '\\' {
        return true;
    }
    if 字.len() >= 2 && 字[0] == '/' && 字[1] == '/' {
        return true;
    }
    if 字.len() < 3 || !(字[0].is_ascii_alphabetic() && 字[1] == ':' && (字[2] == '\\' || 字[2] == '/')) {
        return false;
    }
    /* 后面那一段只剩分隔的（「某处:」那种）不算指到某一格 */
    串.chars().skip(3).any(|c| c != '\\' && c != '/')
}

/// 这一串里有没有「回退一段」的写法：落点认的就是字面上那一条路，带 .. 就不许（免得判完仓内仓外又换一格）
pub fn 带回退(串: &str) -> bool {
    串.replace('\\', "/").split('/').any(|段| 段 == "..")
}

/// 把一串路径归成能逐段比的样子：两种斜杠并成一种、去掉尾巴那道分隔、折大小写
/// （Windows 上路径不分大小写，不折的话「同一格换个写法」就能从闸底下溜过去）
fn 认路(串: &str) -> String {
    let 换 = 串.replace('\\', "/");
    换.trim_end_matches('/').to_lowercase()
}

/// 那条路是不是在那一格里面（含那一格自己）：照 backup.cjs 的 在里子（resolve 完比前缀，少那道斜杠就走眼）
pub fn 在里子(那条: &str, 那一处: &str) -> bool {
    if 那一处.is_empty() {
        return false;
    }
    let a = 认路(那条);
    let b = 认路(那一处);
    a == b || a.starts_with(&format!("{}/", b))
}

/// 还没定落点那一句（照 backup.cjs 的 run 第一道）
pub const 没定那句: &str = "还没定备份到哪一个文件夹";
/// 落点跑进程序这一棵树里那一句（壳新添的一道闸，Electron 那边没有）
pub const 写进仓那句: &str = "备份的落点落在程序这一棵树里，不能往仓里写：";
/// 落点带 .. 那一句（壳新添）
pub const 带回退那句: &str = "备份的落点里带着回退一段的写法，认不出到底写进哪一格：";
/// 落点不是绝对地址那一句（壳新添：这一串是挑目录那一步给的，给不出绝对地址就是没挑成）
pub const 不是绝对那句: &str = "备份的落点得是一串绝对地址：";

/// 落点跑在被抄的其中一处里面那一句（照 backup.cjs：换个文件夹再来）
pub fn 跑在那一处里面(名义: &str, 那一处: &str) -> String {
    format!("备份的落点跑在「{}」那一处里面（{}），换个文件夹再来", 名义, 那一处)
}

/// 这一趟的落点该不该停：回 Some(那一句) 就是不许，None 才放行。
/// 先后次序照 Electron 那一头 —— 先比被抄的那几处（那一句原话得原样报给页面），
/// 再走壳新添的三道（空串、回退写法、不是绝对、跑进这一棵树）。
/// 被抄的几处是 (名字, 那一处) 的一对对，由第三层从页面递进来的 cfg.extra 与默认那一处拼好。
pub fn 落点不许(落点: &str, 这一棵: &str, 被抄的: &[(&str, &str)]) -> Option<String> {
    let 串 = 落点.trim();
    if 串.is_empty() {
        return Some(没定那句.to_string());
    }
    for (名义, 那一处) in 被抄的 {
        if !那一处.is_empty() && 在里子(串, 那一处) {
            return Some(跑在那一处里面(名义, 那一处));
        }
    }
    if 带回退(串) {
        return Some(format!("{}{}", 带回退那句, 串));
    }
    if !是绝对地址(串) {
        return Some(format!("{}{}", 不是绝对那句, 串));
    }
    if !这一棵.is_empty() && 在里子(串, 这一棵) {
        return Some(format!("{}{}", 写进仓那句, 串));
    }
    None
}

/* ---------- 四、收旧份与多大那一句 ---------- */

/// 该收掉哪几颗：只收"自家造的那一颗"里最旧的那几颗，留几份不到就是不收（照 prune：n<=0 直接回）
/// 时间戳那串名字本身就是可排的写法，旧在前，所以排完从头收（照 我的.sort() + slice）
pub fn 该收哪几份(名们: &[String], 留几份: i64) -> Vec<String> {
    if 留几份 <= 0 {
        return Vec::new();
    }
    let mut 我的: Vec<String> = 名们.iter().filter(|x| 是自家造的那一颗(x)).cloned().collect();
    我的.sort();
    if (我的.len() as i64) <= 留几份 {
        return Vec::new();
    }
    我的.truncate(我的.len() - 留几份 as usize);
    我的
}

/// 多大那一句别写死 KB：几十个字的一份试抄出来报「0 KB」，看着就像没抄东西（照 run 最后那一句）
pub fn 报多大(字: u64) -> String {
    if 字 < 1024 {
        format!("{} 字节", 字)
    } else if 字 < 10_485_760 {
        format!("{:.1} KB", 字 as f64 / 1024.0)
    } else {
        format!("{:.1} MB", 字 as f64 / 1_048_576.0)
    }
}

/// 从落点里挑出"上一次"该看的那一串名字：只要合式的目录名，按名字排（旧在前）
/// 照 last 那一颗的 readdir + filter(isDirectory && STAMP_RE)；谁最新就看排最后的那一颗
pub fn 从新到旧(名们: &[String]) -> Vec<String> {
    let mut 合式: Vec<String> = 名们.iter().filter(|x| 是自家造的那一颗(x)).cloned().collect();
    合式.sort();
    合式.reverse();
    合式
}

