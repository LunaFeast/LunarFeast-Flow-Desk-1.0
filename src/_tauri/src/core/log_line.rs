/* 四层里的第一层 · 运行日志那一行的形状（外46 批六第三步补的那一格）
   ----------
   原件在 Electron 主进程里（src\pack\main.cjs 2404~2423 行）：data\logs\ 一天一个文件，
   每行开头是 `FD|`，后面跟着这一行的事。记的都是「当时看不出来、回头才知道」的那些：
   监听起不来、装包留没留出底、名单换算、页面崩了自动重载。
   这一颗只管**一行长什么样、落到哪一个文件**，不碰盘：取时刻与写盘在 tauri_bind::log_cmds。
   三条规矩照原件逐条认：
     一、时刻补零到 `YYYY-MM-DD HH:MM:SS.mmm`（月日时分秒两位、毫秒三位）；
     二、原话里整段换行（连同换行前后的空白）换成一个 ` ⏎ ` —— 日志一行一笔，不许被一句话撑成两行；
     三、换行换完之后截到 900 个字，再长也不留（原件是 .slice(0, 900)）。
   类别为空串、原话为空都照旧出一行（原件那一句是 String(kind || '')，不给它加判断）。 */

/// 每行开头那三个字符（原件 LOG_TAG）
pub const 日志前缀: &str = "FD|";
/// 原话最长留多少个字（换行换成 ⏎ 之后再截）
pub const 最长字: usize = 900;
/// 一天一个文件，文件名就是那一天加 .log
pub const 日志后缀: &str = ".log";

/// 那一天（也是文件名那一串）：`2026-10-11`
pub fn 那天(年: i32, 月: u32, 日: u32) -> String {
    format!("{:04}-{:02}-{:02}", 年, 月, 日)
}

/// 原话洗成一行：换行连同前后空白换成 ` ⏎ `，再截到 900 个字。
/// 一处做不全等（记在 log_cmds 顶上第①条）：原件 .slice(0, 900) 数的是 UTF-16 那一个一个字，
/// 这一头数的是「一个字」—— 中文、假名、常用符号两边一样；带增补平面的字（emoji 那种）
/// 原件算两个、这一头算一个，最多多留一个字，不会截坏一行。
pub fn 洗原话(文: &str) -> String {
    let 换过 = 换行换成记号(文);
    换过.chars().take(最长字).collect()
}

/// 把「任意空白 + 一个换行 + 任意空白」换成 ` ⏎ `（原件那句 /\s*\n\s*/g → ' ⏎ '）
fn 换行换成记号(文: &str) -> String {
    let 字: Vec<char> = 文.chars().collect();
    let mut 出 = String::new();
    let mut 头 = 0usize;
    while 头 < 字.len() {
        if 字[头] != '\n' {
            出.push(字[头]);
            头 += 1;
            continue;
        }
        /* 这一处换行：换行前面那段空白退回去（\s* 那一半），后面那段跳掉，两头合成一个 ' ⏎ ' */
        退空白(&mut 出);
        let mut 尾 = 头 + 1;
        while 尾 < 字.len() && 字[尾].is_whitespace() {
            尾 += 1;
        }
        出.push(' ');
        出.push('⏎');
        出.push(' ');
        头 = 尾;
    }
    出
}

/// 把 出 尾部那段空白抹掉（原件 \s* 里"换行前面"那一半）
fn 退空白(出: &mut String) {
    let 原: Vec<char> = 出.chars().collect();
    let mut 尾 = 原.len();
    while 尾 > 0 && 原[尾 - 1].is_whitespace() {
        尾 -= 1;
    }
    if 尾 == 原.len() {
        return;
    }
    出.clear();
    出.extend(原[..尾].iter());
}

/// 一行日志：回（落到哪一个文件名，这一行的全文）。
/// 时刻由调用方取（纯判断这一格不读时钟，测试才钉得住）；文件名与那一行开头那天是同一个。
pub fn 一行(年: i32, 月: u32, 日: u32, 时: u32, 分: u32, 秒: u32, 毫秒: u32, 类别: &str, 原话: &str) -> (String, String) {
    let 天 = 那天(年, 月, 日);
    let 行 = format!(
        "[{} {:02}:{:02}:{:02}.{:03}] {}{} {}\n",
        天, 时, 分, 秒, 毫秒, 日志前缀, 类别, 洗原话(原话)
    );
    (format!("{}{}", 天, 日志后缀), 行)
}

#[cfg(test)]
mod 验判断 {
    use super::*;

    #[test]
    fn 一行开头是方括号里那天那时刻() {
        let (件, 行) = 一行(2026, 10, 11, 9, 8, 7, 6, "插件", "已装 notes（12KB）");
        assert_eq!(件, "2026-10-11.log");
        assert_eq!(行, "[2026-10-11 09:08:07.006] FD|插件 已装 notes（12KB）\n");
    }

    #[test]
    fn 月日时分秒补两位毫秒补三位() {
        let (_, 行) = 一行(2026, 1, 2, 3, 4, 5, 60, "音乐", "x");
        assert!(行.starts_with("[2026-01-02 03:04:05.060] "), "{}", 行);
    }

    #[test]
    fn 换行连同前后空白换成一个记号() {
        let (_, 行) = 一行(2026, 10, 11, 0, 0, 0, 0, "清单", "重扫 一份\n   两行");
        assert!(行.ends_with("重扫 一份 ⏎ 两行\n"), "{}", 行);
        assert_eq!(行.matches('⏎').count(), 1);
    }

    #[test]
    fn 连续两个换行也只留一个记号() {
        let (_, 行) = 一行(2026, 10, 11, 0, 0, 0, 0, "异常", "一\n\n二");
        assert!(行.ends_with("一 ⏎ 二\n"), "{}", 行);
    }

    #[test]
    fn 行尾那个换行不留成空段() {
        /* 原件那句 .replace 会把结尾的换行也换成 ' ⏎ '，这一头照同一手 —— 差一个尾巴就是差行为 */
        let (_, 行) = 一行(2026, 10, 11, 0, 0, 0, 0, "搬家", "挪完了\n");
        assert!(行.ends_with("挪完了 ⏎ \n"), "{}", 行);
    }

    #[test]
    fn 截到九百个字是换行换完之后再算() {
        let 长 = "啊".repeat(950);
        let (件, 行) = 一行(2026, 10, 11, 0, 0, 0, 0, "音量", &长);
        let 身子 = 行.trim_end_matches('\n').rsplit_once(" FD|音量 ").unwrap().1;
        assert_eq!(身子.chars().count(), 最长字, "{}", 件);
    }

    #[test]
    fn 类别空与原话空都照旧出一行() {
        let (_, 行) = 一行(2026, 10, 11, 1, 1, 1, 1, "", "");
        assert_eq!(行, "[2026-10-11 01:01:01.001] FD| \n");
    }
}
