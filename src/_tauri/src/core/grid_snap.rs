/* 四层里的第一层 · 窗口形状与落点吸到「整格」（外46 三 批九）
   ------------------------------------------------------------
   他要的那一条：「我管你是不是无边框拖拽，反正我要 windows 这种网格吸附拖拽」。
   这一格里只有算法：给窗口现在的尺寸 / 落点，回应该吸到哪儿。不动窗口、不认识壳。

   格子的算法照页面那一份 `Shell.fitGrid()`（`src\_fd\src\fd3-shell.js`）—— 64×36 的相对网格，
   四边各留 1 格、而且四边同一个数（先按两轴里紧的那一轴定出一格的边长）。
   两头不许有两个说法，所以那一份公式在这里原样重写了一遍，并由闸 `gate-snap46.mjs`
   把两边的常数与公式逐字对着钉。

   「窗口边长吸到整格」在这一套里的确切意思：**四边留的那一截和两轴的一格都是整数个物理像素**。
   做到了，页面里卡片折格算出来的边长就是整数 —— 从前那笔「连续放大缩小、拖拽之后操作漂移」
   （外33 第 2 条）的根子就是格子两轴不等边 + 一步落在半像素上。

   数学（列 = 64、行 = 36、四边各留 1 格，所以横轴一共 66 份、竖轴一共 38 份；
   注意两轴的一格本来就不等边，吸的目标是"两边各自成整数"，不是"两格相等"）：
     横轴紧（宽/66 ≤ 高/38）：四边留 = 宽/66，此时 一格宽 = 宽/66、一格高 = (高 - 2·留)/36。
       取 c = 四舍五入(宽/66) → 宽 = 66c；再取 r = 四舍五入((高 - 2c)/36) → 高 = 36r + 2c。
       这一条成立的条件是 c ≤ r（不然紧的是竖轴）。
     竖轴紧：对称，取 r = 四舍五入(高/38) → 高 = 38r；再 宽 = 64c + 2r。成立条件 r ≤ c。
   c = r 时两条算出来一模一样，所以临界尺寸上没有来回跳的缝。 */

/// 网格那三个数，和页面那边共用一份口径
pub const 列: f64 = 64.0;
pub const 行: f64 = 36.0;
pub const 边距格: f64 = 1.0;

/// 横轴一共几份、竖轴一共几份（格子数 + 四边各留的格数）
pub const 横份: f64 = 列 + 边距格 * 2.0; /* 66 */
pub const 竖份: f64 = 行 + 边距格 * 2.0; /* 38 */

/// 按页面 fitGrid 那一套算出两轴的一格是多少（吸之前是浮点，吸之后两轴各自成整数）
pub fn 一格(宽: f64, 高: f64) -> (f64, f64) {
    if !(宽.is_finite()) || !(高.is_finite()) || 宽 <= 0.0 || 高 <= 0.0 {
        return (0.0, 0.0);
    }
    let 外留 = (宽 / 横份).min(高 / 竖份);
    ((宽 - 外留 * 2.0) / 列, (高 - 外留 * 2.0) / 行)
}

/// 是不是已经在档上：四边留的那一截与两轴的一格都是整数物理像素
pub fn 在档上(宽: f64, 高: f64) -> bool {
    if !(宽.is_finite()) || !(高.is_finite()) || 宽 <= 0.0 || 高 <= 0.0 {
        return false;
    }
    let 外留 = (宽 / 横份).min(高 / 竖份);
    let (横, 竖) = 一格(宽, 高);
    let 整 = |x: f64| x >= 1.0 && (x - x.round()).abs() < 0.001;
    整(外留) && 整(横) && 整(竖)
}

/* 横轴紧那一条。回 None = 这一条不成立（或者数值不成），让竖轴那条去算。 */
fn 吸横(宽: f64, 高: f64, 最小宽: f64, 最小高: f64) -> Option<(f64, f64)> {
    let mut c = (宽 / 横份).round();
    if c < 1.0 {
        return None;
    }
    if 横份 * c < 最小宽 {
        c = (最小宽 / 横份).ceil().max(1.0);
    }
    let mut r = ((高 - 2.0 * c) / 行).round();
    if r < 1.0 {
        r = 1.0;
    }
    /* 往上顶最小高度只会加 r，一格宽 = c 不动，所以还在档上 */
    while 行 * r + 2.0 * c < 最小高 {
        r += 1.0;
    }
    if c > r {
        return None;
    }
    Some((横份 * c, 行 * r + 2.0 * c))
}

/* 竖轴紧那一条 */
fn 吸竖(宽: f64, 高: f64, 最小宽: f64, 最小高: f64) -> Option<(f64, f64)> {
    let mut r = (高 / 竖份).round();
    if r < 1.0 {
        return None;
    }
    if 竖份 * r < 最小高 {
        r = (最小高 / 竖份).ceil().max(1.0);
    }
    let mut c = ((宽 - 2.0 * r) / 列).round();
    if c < 1.0 {
        c = 1.0;
    }
    while 列 * c + 2.0 * r < 最小宽 {
        c += 1.0;
    }
    if r > c {
        return None;
    }
    Some((列 * c + 2.0 * r, 竖份 * r))
}

/// 把窗口内层尺寸吸到整格。回 `None` = 不用动（数值不成，或已经在档上）。
/// 最小尺寸由调用那头给（Electron 那边是 720×480 的逻辑值，换成物理像素再传进来），
/// 吸完不够大就沿同一档位往上走，绝不吸出比最小还小的窗。
pub fn 吸尺寸(宽: f64, 高: f64, 最小宽: f64, 最小高: f64) -> Option<(f64, f64)> {
    if !(宽.is_finite()) || !(高.is_finite()) || 宽 <= 0.0 || 高 <= 0.0 {
        return None;
    }
    let 最小宽 = 最小宽.max(0.0);
    let 最小高 = 最小高.max(0.0);
    let 候 = 吸横(宽, 高, 最小宽, 最小高).or_else(|| 吸竖(宽, 高, 最小宽, 最小高))?;
    /* 已经在档上就别动 —— 一动会让窗口在用户手里抖一下，也省一趟来回事件 */
    if (候.0 - 宽).abs() < 0.001 && (候.1 - 高).abs() < 0.001 {
        return None;
    }
    Some(候)
}

/// 一个矩形：工作区（或屏幕）的左、顶、宽、高
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct 矩形 {
    pub 左: f64,
    pub 顶: f64,
    pub 宽: f64,
    pub 高: f64,
}

/// 拖窗口时的落点。三步，顺序就是这条规矩本身：
/// 1. **贴边优先** —— 离工作区任何一边在 `贴边阈值` 以内就吸到那一边上（Windows 就是这手感）；
/// 2. 不贴边时按 `步` 折格（步长给"一格宽、一格高"，吸完窗口的边就压在格线上），原点永远是工作区那一角；
/// 3. 最后**夹住**：整扇窗不许被推到屏外 —— 左右各至少留下 `留住` 那一截，够得着才拖得回来；
///    顶不许越过工作区上沿（无边框时那一条就是唯一够得着的地方），底留同一截。
pub fn 吸位置(
    左: f64,
    顶: f64,
    窗宽: f64,
    窗高: f64,
    步: (f64, f64),
    区: 矩形,
    贴边阈值: f64,
    留住: f64,
) -> (f64, f64) {
    if !(左.is_finite()) || !(顶.is_finite()) || 区.宽 <= 0.0 || 区.高 <= 0.0 {
        return (左, 顶);
    }
    let 右 = 区.左 + 区.宽;
    let 下 = 区.顶 + 区.高;
    let 阈 = 贴边阈值.max(0.0);
    let 新左 = if (左 - 区.左).abs() <= 阈 {
        区.左
    } else if (右 - (左 + 窗宽)).abs() <= 阈 {
        右 - 窗宽
    } else if 步.0 > 0.0 {
        ((左 - 区.左) / 步.0).round() * 步.0 + 区.左
    } else {
        左
    };
    let 新顶 = if (顶 - 区.顶).abs() <= 阈 {
        区.顶
    } else if (下 - (顶 + 窗高)).abs() <= 阈 {
        下 - 窗高
    } else if 步.1 > 0.0 {
        ((顶 - 区.顶) / 步.1).round() * 步.1 + 区.顶
    } else {
        顶
    };
    let 留 = 留住.max(0.0);
    let 夹左 = 新左.clamp(区.左 + 留.min(窗宽) - 窗宽, (右 - 留.min(窗宽)).max(区.左));
    let 夹顶 = 新顶.clamp(区.顶, (下 - 留.min(窗高)).max(区.顶));
    (夹左.round(), 夹顶.round())
}

#[cfg(test)]
mod 验判断 {
    use super::*;

    #[test]
    fn 常数和页面那一份对得上() {
        assert_eq!(横份, 66.0);
        assert_eq!(竖份, 38.0);
    }

    #[test]
    fn 一格照页面那套先紧的那一轴定边距() {
        /* 1280×800：横轴 1280/66 = 19.39 比竖轴 800/38 = 21.05 紧 → 四边留 = 19.39 */
        let (横, 竖) = 一格(1280.0, 800.0);
        assert!((横 - 1280.0 / 66.0).abs() < 0.001);
        assert!(竖 > 横);
        assert_eq!(一格(0.0, 800.0), (0.0, 0.0));
        assert_eq!(一格(-5.0, 800.0), (0.0, 0.0));
    }

    #[test]
    fn 吸完两轴的一格与四边留的都是整数() {
        let (宽, 高) = 吸尺寸(1280.0, 800.0, 720.0, 480.0).unwrap();
        /* 1280 → 一格宽吸到 19：宽 = 66×19 = 1254；高 = 36×21 + 2×19 = 794 */
        assert_eq!(宽, 1254.0);
        assert_eq!(高, 794.0);
        assert_eq!((宽 / 66.0 - 19.0).abs() < 0.001, true);
        let (横, 竖) = 一格(宽, 高);
        assert_eq!(横, 19.0);
        assert_eq!(竖, 21.0);
        assert!(在档上(宽, 高));
    }

    #[test]
    fn 已经在档上的不动() {
        assert_eq!(吸尺寸(1254.0, 794.0, 720.0, 480.0), None);
        assert!(在档上(1254.0, 794.0));
        /* 两轴不等边那一种也认档：66×20 = 1320 配 36×20 + 40 = 760 */
        assert!(在档上(1320.0, 760.0));
        assert_eq!(吸尺寸(1320.0, 760.0, 0.0, 0.0), None);
    }

    #[test]
    fn 临界尺寸两条算出来一模一样() {
        /* c = r 那一档：横 66c、竖 38c，两条分支都成立且相等 —— 没有来回跳的缝 */
        let c = 20.0;
        let 宽 = 66.0 * c;
        let 高 = 38.0 * c;
        assert_eq!(吸横(宽, 高, 0.0, 0.0), Some((宽, 高)));
        assert_eq!(吸竖(宽, 高, 0.0, 0.0), Some((宽, 高)));
        assert_eq!(吸尺寸(宽 + 0.4, 高 - 0.4, 0.0, 0.0), Some((宽, 高)));
    }

    #[test]
    fn 拉长成竖版的窗也吸得动() {
        /* 500×1400 那种竖长条：横轴紧（500/66 = 7.58 < 1400/38 = 36.8） */
        let (宽, 高) = 吸尺寸(500.0, 1400.0, 0.0, 0.0).unwrap();
        let (横, 竖) = 一格(宽, 高);
        assert_eq!(横, 横.round());
        assert_eq!(竖, 竖.round());
        assert!(在档上(宽, 高));
        assert!((宽 - 528.0).abs() < 0.001);
        assert!((高 - 1384.0).abs() < 0.001);
    }

    #[test]
    fn 竖轴真的紧那一支也走得到() {
        /* 900×380：高/38 = 10 比 宽/66 = 13.6 紧 → 走竖轴那一支，高 = 38×10 = 380、宽 = 64c + 20 */
        let (宽, 高) = 吸尺寸(903.0, 381.0, 0.0, 0.0).unwrap();
        assert_eq!(高, 380.0);
        assert_eq!((宽 - 20.0) % 64.0, 0.0);
        assert!(在档上(宽, 高));
    }

    #[test]
    fn 最小尺寸不够就往上走一格而不是吸出更小的窗() {
        /* 最小 1400 宽：66×21 = 1386 不够，就该走到 66×22 = 1452 */
        let (宽, 高) = 吸尺寸(1390.0, 900.0, 1400.0, 0.0).unwrap();
        assert!(宽 >= 1400.0);
        assert_eq!(宽 % 66.0, 0.0);
        assert!(在档上(宽, 高));
        /* 最小高度同理往上走 */
        let (宽, 高) = 吸尺寸(1280.0, 470.0, 0.0, 480.0).unwrap();
        assert!(高 >= 480.0);
        assert!(在档上(宽, 高));
    }

    #[test]
    fn 数值不成就不动() {
        assert_eq!(吸尺寸(0.0, 800.0, 0.0, 0.0), None);
        assert_eq!(吸尺寸(-1.0, 800.0, 0.0, 0.0), None);
        assert_eq!(吸尺寸(f64::NAN, 800.0, 0.0, 0.0), None);
        assert_eq!(吸尺寸(1280.0, f64::INFINITY, 0.0, 0.0), None);
        assert!(!在档上(0.0, 0.0));
    }

    #[test]
    fn 拖窗口先贴边再折格() {
        let 区 = 矩形 { 左: 0.0, 顶: 0.0, 宽: 1920.0, 高: 1080.0 };
        let 步 = (20.0, 20.0);
        /* 离左边 6 像素（阈值 12）→ 吸到左边上 */
        assert_eq!(吸位置(6.0, 300.0, 400.0, 300.0, 步, 区, 12.0, 80.0), (0.0, 300.0));
        /* 右沿离屏幕右 20 像素：阈值 12 够不着，就按步折格（不动） */
        assert_eq!(吸位置(1500.0, 300.0, 400.0, 300.0, 步, 区, 12.0, 80.0), (1500.0, 300.0));
        /* 阈值给到 24 才贴右 */
        assert_eq!(吸位置(1500.0, 300.0, 400.0, 300.0, 步, 区, 24.0, 80.0), (1520.0, 300.0));
        /* 都不贴边就按步折格 */
        assert_eq!(吸位置(377.0, 213.0, 400.0, 300.0, 步, 区, 12.0, 80.0), (380.0, 220.0));
    }

    #[test]
    fn 工作区不是从零点起也照同一原点折格() {
        let 区 = 矩形 { 左: 100.0, 顶: 50.0, 宽: 1000.0, 高: 900.0 };
        let 步 = (20.0, 25.0);
        assert_eq!(吸位置(137.0, 62.0, 400.0, 300.0, 步, 区, 6.0, 80.0), (140.0, 50.0));
    }

    #[test]
    fn 整扇窗推不出屏外() {
        let 区 = 矩形 { 左: 0.0, 顶: 0.0, 宽: 1920.0, 高: 1080.0 };
        let 步 = (20.0, 20.0);
        /* 想把窗推到屏幕左边外：只许推到左边还剩 80 像素 */
        let (左, _) = 吸位置(-500.0, 100.0, 400.0, 300.0, 步, 区, 0.0, 80.0);
        assert_eq!(左, -320.0);
        /* 右边同理：想推到屏幕外，只许推到右边还剩 80 像素 */
        let (右, _) = 吸位置(1900.0, 100.0, 400.0, 300.0, 步, 区, 0.0, 80.0);
        assert_eq!(右, 1840.0);
        /* 只露出 320 像素那种不算过分，不动 */
        let (未动, _) = 吸位置(1600.0, 100.0, 400.0, 300.0, 步, 区, 0.0, 80.0);
        assert_eq!(未动, 1600.0);
        /* 顶部不许越过工作区上沿（无边框时那一条就是唯一够得着的地方） */
        let (_, 顶) = 吸位置(300.0, -200.0, 400.0, 300.0, 步, 区, 0.0, 80.0);
        assert_eq!(顶, 0.0);
    }

    #[test]
    fn 数值不成或没有工作区就原样回() {
        let 区 = 矩形 { 左: 0.0, 顶: 0.0, 宽: 0.0, 高: 0.0 };
        assert_eq!(吸位置(13.0, 17.0, 400.0, 300.0, (20.0, 20.0), 区, 12.0, 80.0), (13.0, 17.0));
        let 回 = 吸位置(
            f64::NAN,
            17.0,
            400.0,
            300.0,
            (20.0, 20.0),
            矩形 { 左: 0.0, 顶: 0.0, 宽: 1000.0, 高: 800.0 },
            12.0,
            80.0,
        );
        /* 原样回：NaN 不能拿 == 比，要问 is_nan */
        assert!(回.0.is_nan());
        assert_eq!(回.1, 17.0);
        /* 步长给 0 = 不折格，只贴边与夹住 */
        let 区 = 矩形 { 左: 0.0, 顶: 0.0, 宽: 1000.0, 高: 800.0 };
        assert_eq!(吸位置(137.0, 17.0, 400.0, 300.0, (0.0, 0.0), 区, 0.0, 80.0), (137.0, 17.0));
    }
}
