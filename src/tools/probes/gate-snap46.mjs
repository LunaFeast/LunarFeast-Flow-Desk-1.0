/* ============================================================
   gate-snap46.mjs · 外46 三 批九：窗口形状与落点吸到整格
   ------------------------------------------------------------
     node src/tools/probes/gate-snap46.mjs
   钉的是这么几件事：
     一、新写的那一格判断上了登记单（在盘上但没登记进 mod.rs 的等于从没编过 —— 这一课已经栽过一次）；
     二、它住在「只算不碰磁盘」那一层：不认识壳、不动盘；
     三、两头一个说法：64×36 与四边留 1 格这三颗数，页面那一份 fitGrid 与壳这一份逐字对得上；
     四、吸附真挂在窗口事件上：Resized 走吸形状、Moved 走吸落点，最大化与全屏那一档不吸；
     五、最小尺寸那一对钉死：壳的开窗口那一处认的与递进去的都是 720×480；
     六、防自己吸自己：两处都留了「差不到一个像素就不动」；
     七、问工作区走的是方法不是字段（那几个字段是私有的，写成字段编不过）；
     八、判断那一格有测试在跑；
     九、反向对照：把登记那一行拿掉，第一条判据必须红。
   ============================================================ */
import { rd, 记账 } from './lib-slice.mjs';

const 台 = 记账('gate-snap46');
const 读 = p => rd(p); /* rd 自己按仓根换算，别再拼一次 ROOT */

const 判断 = 读('src/_tauri/src/core/grid_snap.rs');
const 登记 = 读('src/_tauri/src/core/mod.rs');
const 窗口 = 读('src/_tauri/src/tauri_bind/win_cmds.rs');
const 开窗 = 读('src/_tauri/src/tauri_bind/page_cmds.rs');
const 页面 = 读('src/_fd/src/fd3-shell.js');

/* ---------- 一、登记单 ---------- */
台.题('一、新写那一格上了登记单');
const 上单 = /^pub mod grid_snap;$/m.test(登记);
台.判('core/mod.rs 里有 pub mod grid_snap;（没登记等于从没编过）', 上单);
台.判('判断那一格文件本体在', 判断.includes('pub fn 吸尺寸') && 判断.includes('pub fn 吸位置'));
台.判('登记那一行不是注释（前面不许是 //）', !/\/\/\s*pub mod grid_snap;/.test(登记));

/* ---------- 二、层级规矩 ---------- */
台.题('二、它住在「只算不碰磁盘」那一层');
台.判('不认识壳：整格不出现 tauri', !/tauri/i.test(判断));
台.判('不动盘：不出现 std::fs / File / read_to_string', !/std::fs|File::|read_to_string|write\(/.test(判断));
台.判('不藏本机痕迹：没有盘符', !/[A-Za-z]:[\\/]/.test(判断));

/* ---------- 三、两头一个说法 ---------- */
台.题('三、格子那三颗数两头对得上');
const 页列 = Number((页面.match(/const GRID_COLS\s*=\s*(\d+)/) || [])[1]);
const 页行 = Number((页面.match(/GRID_ROWS\s*=\s*(\d+)/) || [])[1]);
const 页边 = Number((页面.match(/const GRID_COLS\s*=\s*\d+\s*,\s*GRID_ROWS\s*=\s*\d+\s*,\s*GRID_PAD\s*=\s*(\d+)/) || [])[1]);
const 壳列 = Number((判断.match(/pub const 列:\s*f64\s*=\s*(\d+)/) || [])[1]);
const 壳行 = Number((判断.match(/pub const 行:\s*f64\s*=\s*(\d+)/) || [])[1]);
const 壳边 = Number((判断.match(/pub const 边距格:\s*f64\s*=\s*(\d+)/) || [])[1]);
台.数('页面那一份（列 / 行 / 四边留的格）', [页列, 页行, 页边].join(' / '));
台.数('壳这一份（列 / 行 / 四边留的格）', [壳列, 壳行, 壳边].join(' / '));
台.判('三颗数一字不差', 页列 === 壳列 && 页行 === 壳行 && 页边 === 壳边);
/* 页面那份 fitGrid 的式子：外留 = min(W/(列+2·留), H/(行+2·留))，一格 = (W-2·外留)/列 */
const 页式 = /const 外留\s*=\s*Math\.min\(W \/ \(GRID_COLS \+ GRID_PAD \* 2\), H \/ \(GRID_ROWS \+ GRID_PAD \* 2\)\)/.test(页面)
  && /this\.cellW = \(W - 外留 \* 2\) \/ GRID_COLS; this\.cellH = \(H - 外留 \* 2\) \/ GRID_ROWS;/.test(页面);
台.判('页面那一份的式子照旧（壳这份是照着它写的）', 页式);
const 壳式 = /let 外留 = \(宽 \/ 横份\)\.min\(高 \/ 竖份\)/.test(判断)
  && 判断.replace(/\s+/g, '').includes('((宽-外留*2.0)/列,(高-外留*2.0)/行)');
台.判('壳这一份的式子与它同形', 壳式);
台.判('横 66 份、竖 38 份这两颗数是从列与行推出来的，不是又抄了一遍数',
  /pub const 横份: f64 = 列 \+ 边距格 \* 2\.0;/.test(判断) && /pub const 竖份: f64 = 行 \+ 边距格 \* 2\.0;/.test(判断));

/* ---------- 四、吸附真挂在事件上 ---------- */
台.题('四、吸附真挂在窗口事件上');
台.判('Resized 那一支先吸形状再报状态', /WindowEvent::Resized\(尺\) => \{\s*吸形状\(w, 尺\);\s*报状态\(w\.app_handle\(\)\)/.test(窗口));
台.判('Moved 那一支吸落点', /WindowEvent::Moved\(位\) => 吸落点\(w, 位\)/.test(窗口));
台.判('两处开头都挡掉最大化与全屏', (窗口.match(/不该吸\(w\)/g) || []).length >= 2);
台.判('不该吸那一颗真问了这两档', /is_maximized/.test(窗口) && /is_fullscreen/.test(窗口));
台.判('事件回调里改的是窗口本体（set_size / set_position 各一颗）',
  /w\.set_size\(tauri::PhysicalSize::new/.test(窗口) && /w\.set_position\(tauri::PhysicalPosition::new/.test(窗口));
台.判('递给判断那一格的是物理像素（内层尺寸与工作区都按物理）',
  /w\.inner_size\(\)/.test(窗口) && /current_monitor/.test(窗口) && /scale_factor/.test(窗口));

/* ---------- 五、最小尺寸两头一致 ---------- */
台.题('五、最小尺寸两头一致');
const 壳最宽 = Number((窗口.match(/const 最小逻辑: \(f64, f64\) = \((\d+)\.0, (\d+)\.0\)/) || [0, 0, 0])[1]);
const 壳最高 = Number((窗口.match(/const 最小逻辑: \(f64, f64\) = \((\d+)\.0, (\d+)\.0\)/) || [0, 0, 0])[2]);
const 那一对 = [720, 480];
台.数('壳认的最低一对', 壳最宽 + ' × ' + 壳最高);
台.判('那一对就是 720 × 480（开窗口那一处递的是同一对）', 壳最宽 === 那一对[0] && 壳最高 === 那一对[1]);
台.判('开窗口那一处也真把这一对递进去了', /min_inner_size\(720\.0, 480\.0\)/.test(开窗));

/* ---------- 六、防自吸自绕 ---------- */
台.题('六、吸完不再触发第二趟');
台.判('尺寸那一处：差不到一个像素就不动', /if \(宽 as f64 - 现\.0\)\.abs\(\) < 1\.0 && \(高 as f64 - 现\.1\)\.abs\(\) < 1\.0 \{\s*return;/.test(窗口));
台.判('落点那一处：同样差不到一个像素就不动', /if \(新左 - 位\.x\)\.abs\(\) < 1 && \(新顶 - 位\.y\)\.abs\(\) < 1 \{\s*return;/.test(窗口));
/* 在档上 这一颗要是没人叫，cargo 当场报 never used（批九就挨过一次）—— 钉住调用点在 */
台.判('壳里先问一句在档上再算目标（不是只活在测试里）', /grid_snap::在档上\(现\.0, 现\.1\)/.test(窗口));
台.判('判断那一格也认得"已经在档上就别动"', /if \(候\.0 - 宽\)\.abs\(\) < 0\.001 && \(候\.1 - 高\)\.abs\(\) < 0\.001 \{\s*return None;/.test(判断));

/* ---------- 七、Monitor 的写法 ---------- */
台.题('七、问工作区走方法不走字段');
台.判('用的是 work_area()（那几个字段是私有的，写成字段编不过）', /监\.work_area\(\)/.test(窗口) && !/监\.work_area\b(?!\()/.test(窗口));
台.判('拿不到显示器就当没事发生（不拿一片 0 去折格）', /current_monitor\(\)\.ok\(\)\?\?/.test(窗口) && /宽 <= 0\.0 \|\| 区?\.?高 <= 0\.0|尺\.宽 <= 0\.0 \|\| 尺\.高 <= 0\.0/.test(窗口));

/* ---------- 八、测试在跑 ---------- */
台.题('八、判断那一格有测试在跑');
const 测数 = (判断.match(/#\[[^\]]*test\]/g) || []).length;
台.数('grid_snap.rs 里几颗测试', 测数);
台.判('不少于十二颗', 测数 >= 12);
台.判('测试名是中文那句（和别处同一规矩）', /fn 吸完两轴的一格与四边留的都是整数/.test(判断));
台.判('钉住了"临界尺寸两条分支算出同一个结果"（不来回跳）', /fn 临界尺寸两条算出来一模一样/.test(判断));
台.判('钉住了"最小面不够就往上走一格"', /fn 最小尺寸不够就往上走一格而不是吸出更小的窗/.test(判断));
台.判('钉住了"整扇窗推不出屏外"', /fn 整扇窗推不出屏外/.test(判断));

/* ---------- 九、反向对照 ---------- */
台.题('九、反向对照（判据不是空闸）');
const 没登记 = 登记.replace(/^pub mod grid_snap;\n/m, '');
台.判('把登记那一行拿掉，第一条判据就红', !/^pub mod grid_snap;$/m.test(没登记));
const 改了数 = 判断.replace(/pub const 列: f64 = 64\.0;/, 'pub const 列: f64 = 65.0;');
const 壳列2 = Number((改了数.match(/pub const 列:\s*f64\s*=\s*(\d+)/) || [])[1]);
台.判('把壳这一份的列数改成 65，对数那一条就红', !(页列 === 壳列2));
const 没挡 = 窗口.replace(/WindowEvent::Resized\(尺\) => \{\s*吸形状\(w, 尺\);/, 'WindowEvent::Resized(_尺) => {');
台.判('把 Resized 那一支的吸形状拆掉，第四节的判据就红',
  !/WindowEvent::Resized\(尺\) => \{\s*吸形状\(w, 尺\);\s*报状态\(w\.app_handle\(\)\)/.test(没挡));
const 没最小 = 窗口.replace(/const 最小逻辑: \(f64, f64\) = \(720\.0, 480\.0\);/, 'const 最小逻辑: (f64, f64) = (640.0, 480.0);');
台.判('把壳认的最低宽改成 640，第五节那条就红',
  Number((没最小.match(/const 最小逻辑: \(f64, f64\) = \((\d+)\.0/) || [0, 0])[1]) !== 那一对[0]);

台.收尾();
